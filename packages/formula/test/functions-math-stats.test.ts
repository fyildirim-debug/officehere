import { describe, expect, it } from "vitest";
import { calc, err, book } from "./helpers";

const data = { A1: 1, A2: 2, A3: 3, A4: 4, A5: "x", A6: true, B1: 10, B2: 20, B3: 30, B4: 40 };

describe("matematik", () => {
  it("TOPLA ve türevleri", () => {
    expect(calc("=SUM(A1:A6)", data)).toBe(10);
    expect(calc('=SUM(1,"2",TRUE)')).toBe(4);
    expect(err(calc('=SUM("x")'))).toBe("#VALUE!");
    expect(calc("=SUM(A:A)", data)).toBe(10);
    expect(calc("=SUM(1:2)", data)).toBe(33);
    expect(calc("=SUMIF(A1:A4,\">2\")", data)).toBe(7);
    expect(calc("=SUMIF(A1:A4,\">2\",B1:B4)", data)).toBe(70);
    expect(calc("=SUMIF(A1:A4,2,B1)", data)).toBe(20);
    expect(calc('=SUMIFS(B1:B4,A1:A4,">1",A1:A4,"<4")', data)).toBe(50);
    expect(calc("=SUMPRODUCT(A1:A4,B1:B4)", data)).toBe(300);
    expect(err(calc("=SUMPRODUCT(A1:A4,B1:B3)", data))).toBe("#VALUE!");
    expect(calc("=SUMSQ(3,4)")).toBe(25);
    expect(calc("=PRODUCT(A1:A4)", data)).toBe(24);
    expect(calc("=SUMX2MY2({2,3},{1,1})")).toBe(11);
  });
  it("yuvarlama", () => {
    expect(calc("=ROUND(2.5,0)")).toBe(3);
    expect(calc("=ROUND(-2.5,0)")).toBe(-3);
    expect(calc("=ROUND(1.005,2)")).toBe(1.01);
    expect(calc("=ROUND(1234.567,-2)")).toBe(1200);
    expect(calc("=ROUNDUP(3.2,0)")).toBe(4);
    expect(calc("=ROUNDUP(-3.2,0)")).toBe(-4);
    expect(calc("=ROUNDDOWN(3.9,0)")).toBe(3);
    expect(calc("=ROUNDDOWN(-3.9,0)")).toBe(-3);
    expect(calc("=INT(-3.5)")).toBe(-4);
    expect(calc("=TRUNC(-3.5)")).toBe(-3);
    expect(calc("=TRUNC(3.14159,2)")).toBe(3.14);
    expect(calc("=MROUND(10,3)")).toBe(9);
    expect(err(calc("=MROUND(10,-3)"))).toBe("#NUM!");
    expect(calc("=CEILING(2.5,1)")).toBe(3);
    expect(calc("=CEILING(-2.5,-2)")).toBe(-4);
    expect(calc("=CEILING(-2.5,2)")).toBe(-2);
    expect(err(calc("=CEILING(2.5,-1)"))).toBe("#NUM!");
    expect(calc("=FLOOR(2.5,1)")).toBe(2);
    expect(calc("=FLOOR(-2.5,2)")).toBe(-4);
    expect(calc("=FLOOR(1.5,0.1)")).toBe(1.5);
    expect(calc("=CEILING.MATH(-5.5)")).toBe(-5);
    expect(calc("=CEILING.MATH(-5.5,1,1)")).toBe(-6);
    expect(calc("=FLOOR.MATH(-5.5)")).toBe(-6);
    expect(calc("=EVEN(1.5)")).toBe(2);
    expect(calc("=EVEN(-1)")).toBe(-2);
    expect(calc("=ODD(2)")).toBe(3);
    expect(calc("=ODD(-2)")).toBe(-3);
  });
  it("temel fonksiyonlar", () => {
    expect(calc("=MOD(10,3)")).toBe(1);
    expect(calc("=MOD(-10,3)")).toBe(2);
    expect(calc("=MOD(10,-3)")).toBe(-2);
    expect(err(calc("=MOD(1,0)"))).toBe("#DIV/0!");
    expect(calc("=ABS(-5)")).toBe(5);
    expect(calc("=POWER(2,10)")).toBe(1024);
    expect(calc("=SQRT(16)")).toBe(4);
    expect(err(calc("=SQRT(-1)"))).toBe("#NUM!");
    expect(calc("=EXP(0)")).toBe(1);
    expect(calc("=LN(EXP(2))")).toBeCloseTo(2);
    expect(calc("=LOG(1000)")).toBeCloseTo(3);
    expect(calc("=LOG(8,2)")).toBeCloseTo(3);
    expect(calc("=LOG10(0.01)")).toBeCloseTo(-2);
    expect(err(calc("=LN(0)"))).toBe("#NUM!");
    expect(calc("=PI()")).toBeCloseTo(3.14159265);
    expect(calc("=SIGN(-3)")).toBe(-1);
    expect(calc("=FACT(5)")).toBe(120);
    expect(calc("=FACT(0)")).toBe(1);
    expect(err(calc("=FACT(-1)"))).toBe("#NUM!");
    expect(calc("=GCD(12,18,24)")).toBe(6);
    expect(calc("=LCM(4,6)")).toBe(12);
    expect(calc("=QUOTIENT(-7,2)")).toBe(-3);
    expect(calc("=COMBIN(5,2)")).toBe(10);
    expect(calc("=PERMUT(5,2)")).toBe(20);
    expect(calc("=ROMAN(1994)")).toBe("MCMXCIV");
    expect(calc('=ARABIC("MCMXCIV")')).toBe(1994);
    expect(calc("=BASE(255,16)")).toBe("FF");
    expect(calc('=DECIMAL("FF",16)')).toBe(255);
    expect(calc("=RAND()")).toBe(0.25);
    expect(calc("=RANDBETWEEN(1,4)")).toBe(2);
  });
  it("trigonometri", () => {
    expect(calc("=SIN(PI()/2)")).toBeCloseTo(1);
    expect(calc("=COS(0)")).toBe(1);
    expect(calc("=TAN(PI()/4)")).toBeCloseTo(1);
    expect(calc("=DEGREES(PI())")).toBeCloseTo(180);
    expect(calc("=RADIANS(180)")).toBeCloseTo(Math.PI);
    expect(calc("=ATAN2(1,1)")).toBeCloseTo(Math.PI / 4);
    expect(err(calc("=ASIN(2)"))).toBe("#NUM!");
  });
  it("ALTTOPLAM ve TOPLAMA", () => {
    const b = book({ A1: 1, A2: 2, A3: "=SUBTOTAL(9,A1:A2)", A4: 4, A5: "=SUBTOTAL(9,A1:A4)", A6: "=SUBTOTAL(1,A1:A4)", A7: "=AGGREGATE(9,6,B1:B3)", B1: 1, B2: "=1/0", B3: 2 });
    expect(b.get("A3")).toBe(3);
    expect(b.get("A5")).toBe(7);
    expect(b.get("A6")).toBeCloseTo(7 / 3);
    expect(b.get("A7")).toBe(3);
    b.e.setRowHidden(b.s, 1, true);
    b.set("A8", "=SUBTOTAL(109,A1:A4)");
    b.e.recalc();
    expect(b.get("A8")).toBe(5);
  });
  it("matris", () => {
    expect(calc("=MDETERM({1,2;3,4})")).toBeCloseTo(-2);
    expect(calc("=SUM(MMULT({1,2;3,4},{1;1}))")).toBe(10);
    expect(calc("=INDEX(MINVERSE({4,7;2,6}),1,1)")).toBeCloseTo(0.6);
    expect(calc("=SUM(MUNIT(3))")).toBe(3);
  });
});

describe("istatistik", () => {
  it("ortalama ve sayım", () => {
    expect(calc("=AVERAGE(A1:A6)", data)).toBe(2.5);
    expect(calc("=AVERAGEA(A1:A6)", data)).toBeCloseTo(11 / 6);
    expect(err(calc("=AVERAGE(C1:C3)"))).toBe("#DIV/0!");
    expect(calc('=AVERAGEIF(A1:A4,">=2",B1:B4)', data)).toBe(30);
    expect(calc('=AVERAGEIFS(B1:B4,A1:A4,">1",A1:A4,"<>3")', data)).toBe(30);
    expect(calc("=COUNT(A1:A6)", data)).toBe(4);
    expect(calc('=COUNT(1,"2","x",TRUE)')).toBe(3);
    expect(calc("=COUNTA(A1:A6)", data)).toBe(6);
    expect(calc("=COUNTBLANK(A1:A10)", data)).toBe(4);
    expect(calc('=COUNTIF(A1:A6,">1")', data)).toBe(3);
    expect(calc('=COUNTIF(A1:A6,"x")', data)).toBe(1);
    expect(calc('=COUNTIF(A1:A6,"X*")', data)).toBe(1);
    expect(calc('=COUNTIF(A1:A10,"")', data)).toBe(4);
    expect(calc('=COUNTIF(A1:A6,"<>x")', data)).toBe(5);
    expect(calc('=COUNTIFS(A1:A4,">1",B1:B4,"<40")', data)).toBe(2);
    expect(calc('=COUNTIF(C1:C3,"?b")', { C1: "ab", C2: "abc", C3: "cb" })).toBe(2);
    expect(calc('=COUNTIF(C1:C3,"~*")', { C1: "*", C2: "a", C3: "**" })).toBe(1);
  });
  it("min/maks/ortanca/mod", () => {
    expect(calc("=MIN(A1:A6)", data)).toBe(1);
    expect(calc("=MAX(A1:A6)", data)).toBe(4);
    expect(calc("=MAX(C1:C2)")).toBe(0);
    expect(calc("=MAXA(-1,TRUE)")).toBe(1);
    expect(calc('=MINIFS(B1:B4,A1:A4,">1")', data)).toBe(20);
    expect(calc('=MAXIFS(B1:B4,A1:A4,"<3")', data)).toBe(20);
    expect(calc("=MEDIAN(1,2,3,4)")).toBe(2.5);
    expect(calc("=MEDIAN(3,1,2)")).toBe(2);
    expect(calc("=MODE(1,2,2,3,3,3)")).toBe(3);
    expect(err(calc("=MODE(1,2,3)"))).toBe("#N/A");
    expect(calc("=LARGE(A1:A4,2)", data)).toBe(3);
    expect(calc("=SMALL(A1:A4,1)", data)).toBe(1);
    expect(err(calc("=LARGE(A1:A4,5)", data))).toBe("#NUM!");
    expect(calc("=SUM(LARGE(A1:A4,{1,2}))", data)).toBe(7);
  });
  it("sapma ve varyans", () => {
    expect(calc("=STDEV(2,4,4,4,5,5,7,9)")).toBeCloseTo(2.13809, 4);
    expect(calc("=STDEV.P(2,4,4,4,5,5,7,9)")).toBe(2);
    expect(calc("=VAR.S(1,2,3,4)")).toBeCloseTo(1.666667, 5);
    expect(calc("=VAR.P(1,2,3,4)")).toBe(1.25);
    expect(err(calc("=STDEV(1)"))).toBe("#DIV/0!");
  });
  it("sıra, yüzdebirlik, dörttebirlik", () => {
    expect(calc("=RANK(3,A1:A4)", data)).toBe(2);
    expect(calc("=RANK(3,A1:A4,1)", data)).toBe(3);
    expect(calc("=RANK.AVG(2,{1,2,2,3})")).toBe(2.5);
    expect(err(calc("=RANK(9,A1:A4)", data))).toBe("#N/A");
    expect(calc("=PERCENTILE({1,2,3,4},0.25)")).toBe(1.75);
    expect(calc("=PERCENTILE.EXC({1,2,3,4},0.25)")).toBe(1.25);
    expect(calc("=QUARTILE({1,2,3,4,5},1)")).toBe(2);
    expect(calc("=QUARTILE.EXC({1,2,3,4,5,6,7},1)")).toBe(2);
    expect(calc("=PERCENTRANK({1,2,3,4},3)")).toBeCloseTo(0.666, 3);
  });
  it("korelasyon ve regresyon", () => {
    expect(calc("=CORREL(A1:A4,B1:B4)", data)).toBeCloseTo(1);
    expect(calc("=SLOPE(B1:B4,A1:A4)", data)).toBeCloseTo(10);
    expect(calc("=INTERCEPT(B1:B4,A1:A4)", data)).toBeCloseTo(0);
    expect(calc("=FORECAST(5,B1:B4,A1:A4)", data)).toBeCloseTo(50);
    expect(calc("=RSQ(B1:B4,A1:A4)", data)).toBeCloseTo(1);
    expect(calc("=COVARIANCE.P({1,2,3},{1,2,3})")).toBeCloseTo(2 / 3);
    expect(calc("=GEOMEAN(2,8)")).toBeCloseTo(4);
    expect(calc("=HARMEAN(1,2,4)")).toBeCloseTo(12 / 7);
    expect(calc("=AVEDEV(1,2,3,4)")).toBe(1);
    expect(calc("=DEVSQ(1,2,3)")).toBe(2);
    expect(calc("=TRIMMEAN({1,2,3,4,100},0.4)")).toBe(3);
    expect(calc("=SUM(FREQUENCY({1,2,3,4,5},{2,4}))")).toBe(5);
    expect(calc("=INDEX(FREQUENCY({1,2,3,4,5},{2,4}),2)")).toBe(2);
  });
  it("dağılımlar", () => {
    expect(calc("=NORM.S.DIST(0,TRUE)")).toBeCloseTo(0.5);
    expect(calc("=NORM.S.DIST(1.96,TRUE)")).toBeCloseTo(0.975, 3);
    expect(calc("=NORM.S.INV(0.975)")).toBeCloseTo(1.959964, 5);
    expect(calc("=NORM.DIST(42,40,1.5,TRUE)")).toBeCloseTo(0.908789, 5);
    expect(calc("=NORM.INV(0.908789,40,1.5)")).toBeCloseTo(42, 4);
    expect(calc("=BINOM.DIST(6,10,0.5,FALSE)")).toBeCloseTo(0.205078, 5);
    expect(calc("=POISSON.DIST(2,5,FALSE)")).toBeCloseTo(0.084224, 5);
    expect(calc("=EXPON.DIST(0.2,10,TRUE)")).toBeCloseTo(0.864665, 5);
    expect(calc("=STANDARDIZE(42,40,1.5)")).toBeCloseTo(1.333333, 5);
  });
});
