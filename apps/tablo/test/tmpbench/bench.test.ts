import { it } from "vitest";
import { readFileSync, appendFileSync } from "node:fs";
import { Controller } from "../../src/controller";
import { readXlsx } from "../../src/io/xlsx";
import * as D from "../../src/actions/data";

const log = (...a: unknown[]) => appendFileSync("/tmp/claude-0/-home-user-officehere/8aa89398-b631-5201-a590-83027cc0aeca/scratchpad/tablo3/bench.log", a.map(String).join(" ") + "\n");
it("bench filter 50k", async () => {
  const buf = readFileSync("/tmp/claude-0/-home-user-officehere/8aa89398-b631-5201-a590-83027cc0aeca/scratchpad/kabul-tablo/files_in/buyuk50k.xlsx");
  let t = performance.now();
  const wb = await readXlsx(buf.buffer.slice(buf.byteOffset, buf.byteOffset + buf.byteLength) as ArrayBuffer);
  log("read", performance.now() - t);
  const ctl = new Controller();
  t = performance.now();
  ctl.load(wb, "b", null);
  log("load", performance.now() - t);
  ctl.selectCell(0, 2);
  t = performance.now();
  D.toggleAutoFilter(ctl);
  log("toggle", performance.now() - t, ctl.sheet.autoFilter?.range);
  const f = ctl.sheet.autoFilter!;
  t = performance.now();
  const cv = D.columnValues(ctl.wb, ctl.sheet, f, 2);
  log("colvals", performance.now() - t, cv.values.slice(0, 5));
  t = performance.now();
  D.setColumnFilter(ctl, f, 2, { kind: "values", values: ["İzmir"], blanks: false });
  log("setfilter", performance.now() - t, ctl.sheet.filterHidden.size);
  t = performance.now();
  D.clearAllFilters(ctl);
  log("clear", performance.now() - t, ctl.sheet.filterHidden.size);
  t = performance.now();
  D.quickSort(ctl, true);
  log("sort", performance.now() - t);
  t = performance.now();
  ctl.ops.setHidden(ctl.sheet, "row", Array.from({ length: 40000 }, (_, i) => i + 5), true);
  log("hide", performance.now() - t);
  t = performance.now();
  ctl.ops.insertRows(ctl.sheet, 10, 5);
  log("insert", performance.now() - t);
  t = performance.now();
  ctl.ops.deleteRows(ctl.sheet, 10, 5);
  log("delete", performance.now() - t);
  t = performance.now();
  ctl.ops.undo();
  log("undo", performance.now() - t);
}, 600000);
